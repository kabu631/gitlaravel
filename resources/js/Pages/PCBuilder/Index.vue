<template>
  <AppLayout>
    <Breadcrumbs :items="[{ label: 'PC Builder' }]" />
    <header class="mb-10 mt-4 max-w-2xl">
      <h1 class="text-3xl font-semibold tracking-tight text-fg sm:text-4xl">PC Builder</h1>
      <p class="mt-2 text-fg-muted">
        Tell us your budget and what you’ll use the PC for. You’ll get a compatible parts list with estimated prices in Nepal — generated by AI, so double-check before you buy.
      </p>
    </header>

    <!-- Main Configurator Grid -->
    <div class="grid grid-cols-1 lg:grid-cols-5 gap-8">
      <!-- Form Controls (2 cols) -->
      <div class="lg:col-span-2 space-y-6">
        <!-- Budget & Purpose Card -->
        <div class="glass-card bg-surface border border-line rounded-xl p-6 shadow-xs">
          <h2 class="mb-4 font-semibold text-fg">What do you need?</h2>

          <div class="space-y-4">
            <!-- Purpose selector -->
            <div>
              <label class="label">Main use</label>
              <div class="grid grid-cols-2 gap-2">
                <button
                  v-for="p in purposes"
                  :key="p.value"
                  type="button"
                  @click="form.purpose = p.value"
                  :class="form.purpose === p.value
                    ? 'bg-fg text-canvas border-fg font-semibold shadow-xs'
                    : 'bg-surface-2 border-line text-fg-muted hover:border-line-strong'"
                  class="border rounded-xl p-2.5 text-xs transition text-left flex items-center gap-2 cursor-pointer"
                >
                  <component :is="p.icon" class="w-3.5 h-3.5 shrink-0" />
                  <span class="truncate">{{ p.label }}</span>
                </button>
              </div>
            </div>

            <!-- Budget input -->
            <div>
              <label class="label">Budget (Rs)</label>
              <div class="relative">
                <span class="absolute left-3 top-1/2 -translate-y-1/2 text-sm text-fg-subtle">Rs</span>
                <input
                  v-model.number="form.budget"
                  type="number"
                  min="25000"
                  step="5000"
                  class="input pl-10"
                  placeholder="e.g. 150000"
                />
              </div>

              <!-- Quick Presets -->
              <div class="flex gap-1.5 mt-2.5 flex-wrap">
                <button
                  v-for="b in budgetPresets"
                  :key="b"
                  type="button"
                  @click="form.budget = b"
                  :class="form.budget === b ? 'bg-fg text-canvas font-semibold' : 'bg-surface-2 text-fg-muted hover:bg-surface-3'"
                  class="px-2.5 py-1 rounded-lg text-2xs font-semibold transition cursor-pointer"
                >
                  {{ formatBudget(b) }}
                </button>
              </div>
            </div>
          </div>
        </div>

        <!-- Optional Component Preferences -->
        <div class="glass-card bg-surface border border-line rounded-xl p-6 shadow-xs">
          <div class="flex items-center justify-between mb-2">
            <h2 class="font-semibold text-fg">Parts you already have</h2>
            <span class="text-2xs uppercase font-semibold text-fg-subtle bg-surface-2 px-2 py-0.5 rounded">Optional</span>
          </div>
          <p class="text-xs text-fg-subtle mb-4">Leave these empty to let the builder choose, or fill in parts you want to keep.</p>

          <div class="space-y-2.5">
            <div v-for="comp in components" :key="comp.key">
              <label class="block text-2xs font-semibold text-fg-subtle mb-1 flex items-center gap-1.5">
                <component :is="comp.icon" class="w-3 h-3 text-fg-subtle" />
                <span>{{ comp.label }}</span>
              </label>
              <input
                v-model="form[comp.key]"
                type="text"
                :placeholder="comp.placeholder"
                class="input h-9"
              />
            </div>
          </div>
        </div>

        <!-- Submit Button -->
        <button
          @click="getRecommendation"
          :disabled="loading || !form.budget || !form.purpose"
          class="w-full py-3.5 rounded-xl font-semibold transition text-xs flex items-center justify-center gap-2 cursor-pointer shadow-sm"
          :class="loading || !form.budget || !form.purpose
            ? 'bg-surface-3 text-fg-subtle cursor-not-allowed'
            : 'bg-fg hover:bg-fg/85 text-canvas'"
        >
          <Loader2 v-if="loading" class="w-4 h-4 animate-spin" />
          <Bot v-else class="w-4 h-4" />
          <span>{{ loading ? 'Building your list…' : 'Suggest a build' }}</span>
        </button>

        <button
          v-if="recommendation || error"
          @click="reset"
          class="w-full py-2 rounded-xl text-xs text-fg-subtle hover:text-fg transition"
        >
          Start over
        </button>
      </div>

      <!-- Results Display (3 cols) -->
      <div class="lg:col-span-3">
        <!-- Initial Placeholder State -->
        <div
          v-if="!recommendation && !error && !loading"
          class="h-full min-h-[380px] glass-card bg-surface border border-dashed border-line-strong rounded-xl flex flex-col items-center justify-center text-center p-8 sm:p-12 shadow-xs"
        >
          <div class="w-16 h-16 rounded-xl bg-surface-2 text-fg-subtle border border-line flex items-center justify-center mb-4">
            <Bot class="w-8 h-8" />
          </div>
          <h3 class="text-lg font-semibold text-fg mb-2">Build Recommendations Will Appear Here</h3>
          <p class="text-xs text-fg-subtle max-w-sm leading-relaxed mb-6">
            Choose your budget and workload purpose on the left. The AI will provide part-by-part recommendations with Kathmandu market estimates.
          </p>
          <div class="flex items-center gap-4 text-xs text-fg-subtle">
            <span class="flex items-center gap-1"><Check class="w-3.5 h-3.5 text-positive" /> Bottleneck Check</span>
            <span class="flex items-center gap-1"><Check class="w-3.5 h-3.5 text-positive" /> Wattage Estimate</span>
            <span class="flex items-center gap-1"><Check class="w-3.5 h-3.5 text-positive" /> Local Pricing</span>
          </div>
        </div>

        <!-- Loading State -->
        <div
          v-if="loading"
          class="h-full min-h-[380px] glass-card bg-surface border border-line rounded-xl flex flex-col items-center justify-center text-center p-12 shadow-sm"
        >
          <div class="w-16 h-16 rounded-xl bg-surface-2 text-fg-subtle flex items-center justify-center mb-4 animate-bounce">
            <Cpu class="w-8 h-8" />
          </div>
          <h3 class="text-lg font-semibold text-fg mb-1">Optimizing Component Selection...</h3>
          <p class="text-xs text-fg-subtle max-w-sm">
            Simulating workload scenarios, checking memory frequencies, and matching latest Nepal component rates.
          </p>
          <div class="mt-6 flex gap-1.5">
            <div v-for="i in 3" :key="i" class="w-2 h-2 bg-blue-500 rounded-full animate-bounce" :style="`animation-delay:${(i-1)*0.15}s`" />
          </div>
        </div>

        <!-- Error State -->
        <div
          v-if="error && !loading"
          class="glass-card bg-negative-soft border border-negative/25 rounded-xl p-8 text-center"
        >
          <p class="text-xs font-semibold text-negative uppercase tracking-wider mb-1">Recommendation Notice</p>
          <p class="text-sm text-fg mb-4">{{ error }}</p>
          <button @click="getRecommendation" class="px-4 py-2 bg-fg text-canvas rounded-xl text-xs font-semibold shadow-xs">
            Retry Recommendation
          </button>
        </div>

        <!-- Recommendation Output Card -->
        <div
          v-if="recommendation && !loading"
          class="glass-card bg-surface border border-line rounded-xl overflow-hidden shadow-md"
        >
          <div class="bg-navy-900 px-6 py-4 flex items-center justify-between border-b border-slate-800">
            <div>
              <div class="flex items-center gap-2">
                <Bot class="w-4 h-4 text-brand-400" />
                <h3 class="font-semibold text-sm text-white">Recommended Build Plan</h3>
              </div>
              <p class="text-2xs text-slate-300 mt-0.5">
                {{ purposeLabel }} · Budget: Rs. {{ Number(form.budget || 0).toLocaleString('en-NP') }}
              </p>
            </div>
            <button
              @click="copyRecommendation"
              class="text-xs text-slate-300 hover:text-white px-3 py-1.5 rounded-lg bg-white/10 hover:bg-white/15 transition flex items-center gap-1.5 cursor-pointer"
            >
              <Copy class="w-3.5 h-3.5" />
              <span>{{ copied ? 'Copied!' : 'Copy Build' }}</span>
            </button>
          </div>

          <div class="p-6 overflow-auto max-h-[70vh]">
            <div
              class="prose prose-sm dark:prose-invert max-w-none text-xs leading-relaxed prose-th:text-xs prose-th:font-semibold prose-th:bg-slate-50 dark:prose-th:bg-slate-800/60 prose-td:py-2.5 prose-table:border prose-table:border-slate-200 dark:prose-table:border-slate-800 prose-headings:font-heading prose-headings:font-semibold prose-headings:text-slate-900 dark:prose-headings:text-white"
              v-html="renderMarkdown(recommendation)"
            />
          </div>

          <div class="border-t border-line px-6 py-4 bg-surface-2 flex items-center justify-between">
            <span class="text-xs text-fg-subtle">Need customized assembly or warranty help?</span>
            <Link :href="route('pages.contact')" class="text-xs font-semibold text-accent-text hover:underline">
              Contact Tech Support →
            </Link>
          </div>
        </div>
      </div>
    </div>
  </AppLayout>
</template>

<script setup>
import AppLayout from '@/Layouts/AppLayout.vue'
import { Link } from '@inertiajs/vue3'
import { ref, computed } from 'vue'
import axios from 'axios'
import { marked } from 'marked'
import {
  Gamepad2, Briefcase, BookOpen, Clapperboard, Radio, Coins,
  Cpu, Monitor, HardDrive, Layers, Zap, Fan, Box, Bot,
  Sparkles, Copy, Check, Loader2 } from 'lucide-vue-next'
import Breadcrumbs from '@/Components/Breadcrumbs.vue'

marked.setOptions({ breaks: true, gfm: true })
function renderMarkdown(text) {
  return marked.parse(text ?? '')
}

const form = ref({
  purpose: '', budget: null,
  cpu: '', gpu: '', ram: '', storage: '', motherboard: '', psu: '', cooling: '', case: ''
})
const recommendation = ref('')
const loading = ref(false)
const error   = ref('')
const copied  = ref(false)

const purposes = [
  { value: 'Gaming',         label: 'Gaming',       icon: Gamepad2 },
  { value: 'Workstation',    label: 'Workstation',  icon: Briefcase },
  { value: 'Office & Study', label: 'Office/Study', icon: BookOpen },
  { value: 'Video Editing',  label: 'Editing',      icon: Clapperboard },
  { value: 'Streaming',      label: 'Streaming',    icon: Radio },
  { value: 'Budget Build',   label: 'Budget',       icon: Coins },
]

const budgetPresets = [60000, 90000, 120000, 150000, 200000, 300000]

const components = [
  { key: 'cpu',         label: 'CPU / Processor',  icon: Cpu,       placeholder: 'e.g. AMD Ryzen 5 7600X' },
  { key: 'gpu',         label: 'Graphics Card',    icon: Monitor,   placeholder: 'e.g. NVIDIA RTX 4060' },
  { key: 'ram',         label: 'Memory (RAM)',     icon: HardDrive, placeholder: 'e.g. 16GB DDR5 6000MHz' },
  { key: 'storage',     label: 'SSD Storage',      icon: HardDrive, placeholder: 'e.g. 1TB NVMe Gen4' },
  { key: 'motherboard', label: 'Motherboard',      icon: Layers,    placeholder: 'e.g. B650M ATX' },
  { key: 'psu',         label: 'Power Supply',     icon: Zap,       placeholder: 'e.g. 650W 80+ Bronze' },
  { key: 'cooling',     label: 'CPU Cooler',       icon: Fan,       placeholder: 'e.g. Air Cooler / 240mm AIO' },
  { key: 'case',        label: 'Cabinet Case',     icon: Box,       placeholder: 'e.g. Mesh Front ATX' },
]

const purposeLabel = computed(() => purposes.find(p => p.value === form.value.purpose)?.label ?? '')

function formatBudget(b) {
  return b >= 100000 ? `Rs. ${b / 100000} Lakh` : `Rs. ${b / 1000}K`
}

async function getRecommendation() {
  if (!form.value.budget || !form.value.purpose) return
  loading.value = true
  error.value   = ''
  recommendation.value = ''

  try {
    const { data } = await axios.post(route('pcbuilder.recommend'), form.value)
    recommendation.value = data.recommendation
  } catch (e) {
    error.value = e.response?.data?.error ?? 'Unable to connect to AI service. Please try again.'
  } finally {
    loading.value = false
  }
}

function copyRecommendation() {
  if (!recommendation.value) return
  navigator.clipboard.writeText(recommendation.value).then(() => {
    copied.value = true
    setTimeout(() => { copied.value = false }, 2000)
  })
}

function reset() {
  form.value = { purpose: '', budget: null, cpu: '', gpu: '', ram: '', storage: '', motherboard: '', psu: '', cooling: '', case: '' }
  recommendation.value = ''
  error.value = ''
}
</script>
